from fastapi import WebSocket, WebSocketDisconnect
import uuid
from backend.api.websocket_manager import WebSocketManager
# from backend.core.application import application


websocket_manager = WebSocketManager()


async def websocket_endpoint(
    websocket: WebSocket,
):

    await websocket_manager.connect(
        websocket
    )
    
    from backend.core.application import application
    await websocket_manager.broadcast(
        {
            "event_type": "connection",
            "agent": "system",
            "data": {
                "message": "Connected to Local AI Office"
            },
        }
    )
    
    try:

        while True:

            message = await websocket.receive_text()

            print(
                f"\nWEBSOCKET RECEIVED: {message}"
            )
            request_id = str(uuid.uuid4())
            # --------------------------------------------------
            # Send the user's request to the Boss
            # --------------------------------------------------

            await websocket.send_json(
                {
                    "event_type": "user_request",
                    "agent": "user",
                    "data": {
                        "message": message
                    },
                }
            )

            # --------------------------------------------------
            # Run the existing BossAgent
            # --------------------------------------------------

            result = await application.boss.run(message)

            # Persist and publish any project generated by Coder.
            from backend.api.routes import persist_coder_artifact

            await persist_coder_artifact(request_id)
            # --------------------------------------------------
            # Send Boss final answer back to client
            # --------------------------------------------------

            await websocket.send_json(
                {
                    "event_type": "boss_response",
                    "agent": "boss",
                    "data": {
                        "message": result
                    },
                }
            )

    
    except WebSocketDisconnect:
        print("\nWEBSOCKET: Client disconnected normally.")

    except Exception as exc:
        print(f"\nWEBSOCKET ERROR: {type(exc).__name__}: {exc}")

    finally:
        websocket_manager.disconnect(websocket)